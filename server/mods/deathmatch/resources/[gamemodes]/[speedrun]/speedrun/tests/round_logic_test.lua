local function newRound(opts)
  return RoundLogic.new(opts or {timeLimitMs = 900000, extraAfterFirstMs = 180000})
end

test("finish returns elapsed since go", function()
  local r = newRound(); r:addPlayer("a"); r:start(0); r:go(1000)
  assertEq(r:finish("a", 61000), 60000)
end)

test("fail counts only while running", function()
  local r = newRound(); r:addPlayer("a"); r:start(0)
  assertEq(r:fail("a", 10), false)
  assertEq(r.players.a.failures, 0)
  r:go(1000)
  assertEq(r:fail("a", 2000), true)
  assertEq(r.players.a.failures, 1)
end)

test("death outside running is not a failure", function()
  local r = newRound(); r:addPlayer("a"); r:start(0); r:go(0)
  r:quit("a", 5)
  r:tick(5)
  assertEq(r.state, "results")
  assertEq(r:fail("a", 10), false)
end)

test("extra time after first finish", function()
  local r = newRound({timeLimitMs = 900000, extraAfterFirstMs = 180000})
  r:addPlayer("a"); r:addPlayer("b"); r:start(0); r:go(0)
  r:finish("a", 100000)
  assertEq(r:deadline(), 280000)
end)

test("deadline never exceeds limit", function()
  local r = newRound({timeLimitMs = 900000, extraAfterFirstMs = 180000})
  r:addPlayer("a"); r:addPlayer("b"); r:start(0); r:go(0)
  r:finish("a", 800000)
  assertEq(r:deadline(), 900000)
end)

test("ends when everyone done", function()
  local r = newRound(); r:addPlayer("a"); r:addPlayer("b"); r:start(0); r:go(0)
  r:finish("a", 1000)
  assertEq(r:tick(1500), "running")
  r:quit("b", 2000)
  assertEq(r:tick(2000), "results")
end)

test("quit counts as dnf and can end round", function()
  local r = newRound(); r:addPlayer("a"); r:start(0); r:go(0)
  r:quit("a", 500)
  assertEq(r.players.a.dnf, true)
  assertEq(r:tick(500), "results")
end)

test("finish twice ignored", function()
  local r = newRound(); r:addPlayer("a"); r:addPlayer("b"); r:start(0); r:go(0)
  assertEq(r:finish("a", 1000), 1000)
  assertEq(r:finish("a", 2000), nil)
  assertEq(r.players.a.finishedMs, 1000)
end)

test("tick ends at deadline", function()
  local r = newRound(); r:addPlayer("a"); r:start(0); r:go(0)
  assertEq(r:tick(899999), "running")
  assertEq(r:tick(900000), "results")
end)

test("rejoin resets run and startPlayer sets own timer", function()
  local r = newRound(); r:addPlayer("a"); r:start(0); r:go(1000)
  r:quit("a", 2000)
  assertEq(r.players.a.dnf, true)
  assertEq(r:rejoin("a"), true)
  assertEq(r.players.a.dnf, false)
  assertEq(r.players.a.finishedMs, nil)
  assertEq(r.players.a.failures, 0)
  assertEq(r.players.a.startMs, nil)
  r:startPlayer("a", 5000)
  assertEq(r:finish("a", 56000), 51000)
end)
